"""
Phase 4 Pre-flight §10 Encoder Differential Verification Script.

Ensures that the SMT formulas generated by encoders (IAM, Security Group, Reachability)
match ground-truth satisfiability expectations directly, blocking benchmark execution
if encoder defects are detected.
"""

from typing import List, Dict, Any, Tuple
from z3 import Solver, sat, unsat, unknown

from parser.hcl_parser import parse_file, build_graph
from parser.arm_parser import parse_arm_file
from graph.azure_trust_graph import build_azure_trust_graph
from parser.graph import ResourceGraph, Unresolved
from parser.attachments import resolve_rule_attachments
from parser.references import resolve_resource_references
from encoder.iam_encoder import encode_iam_scope_symbolic
from encoder.sg_encoder import encode_sg_resource_symbolic
from encoder.reachability_encoder import encode_reachability_bmc
from encoder.hop_bound import compute_hop_bound
from graph.trust_graph import build_trust_graph
from solver.engine import VerificationEngine


def run_differential_check(test_cases: List[Dict[str, Any]]) -> Tuple[bool, List[str]]:
    """
    Evaluates raw SMT formula satisfiability against expected_engine_state for test cases.
    Returns (success_flag, error_messages).
    """
    errors = []
    engine = VerificationEngine(use_cache=False)
    
    for case in test_cases:
        if case.get("ambiguity", {}).get("is_ambiguous", False):
            continue
            
        file_path = case.get("file")
        expected_state = case.get("expected_engine_state")
        vulnerability_class = case.get("vulnerability_class")
        target_resource_id = case.get("resource_id")
        
        if not file_path or not expected_state:
            continue
            
        try:
            if file_path.endswith(".json"):
                graph = parse_arm_file(file_path)
                build_azure_trust_graph(graph)
            else:
                parsed = parse_file(file_path)
                graph = build_graph(parsed)
                graph = resolve_resource_references(graph)
                graph = resolve_rule_attachments(graph)
                build_azure_trust_graph(graph)
            
            if vulnerability_class in ("AZURE_NSG_EXPOSURE", "AZURE_RBAC_ESCALATION", "AZURE_GOVERNANCE_POLICY_VIOLATION"):
                eval_results = engine.verify_graph(graph)
                pattern_map = {
                    "AZURE_NSG_EXPOSURE": "NSG_OVER_EXPOSURE",
                    "AZURE_RBAC_ESCALATION": "PRIVILEGE_ESCALATION_REACHABILITY",
                    "AZURE_GOVERNANCE_POLICY_VIOLATION": "AZURE_GOVERNANCE_POLICY_VIOLATION",
                }
                target_pat = pattern_map.get(vulnerability_class, vulnerability_class)
                matching = [r for r in eval_results if r.pattern == target_pat]
                if not matching:
                    matching = eval_results

                if any(r.status == "SAT" for r in matching):
                    actual_state = "SAT"
                elif any(r.status == "UNRESOLVABLE" for r in matching):
                    actual_state = "UNRESOLVABLE"
                else:
                    actual_state = "UNSAT"

                if actual_state != expected_state:
                    errors.append(f"[Azure Differential Mismatch] {file_path}: expected {expected_state}, got {actual_state}")
                continue

            if vulnerability_class == "SG_EXPOSURE":
                sg_rules = [r for r in graph.resources.values() if r.type in ("aws_security_group", "aws_security_group_rule")]
                if not sg_rules:
                    errors.append(f"[SG Differential Error] No SG resources found in {file_path}")
                    continue
                
                target_rule = sg_rules[0]
                if target_resource_id and target_resource_id in graph.resources:
                    target_rule = graph.resources[target_resource_id]
                    
                solver = Solver()
                res_tuple = encode_sg_resource_symbolic(target_rule)
                if isinstance(res_tuple, Unresolved):
                    actual_state = "UNRESOLVABLE"
                else:
                    ip_v, expr = res_tuple
                    solver.add(expr)
                    res = solver.check()
                    actual_state = "SAT" if res == sat else ("UNSAT" if res == unsat else "UNKNOWN")
                
                if actual_state != expected_state:
                    errors.append(f"[SG Differential Mismatch] {file_path} ({target_rule.address}): expected {expected_state}, got {actual_state}")

            elif vulnerability_class == "IAM_WILDCARD_GRANT":
                iam_policies = [r for r in graph.resources.values() if r.type in ("aws_iam_policy", "aws_iam_role_policy", "aws_iam_role")]
                if not iam_policies:
                    errors.append(f"[IAM Differential Error] No IAM resources found in {file_path}")
                    continue
                
                target_policy = iam_policies[0]
                if target_resource_id and target_resource_id in graph.resources:
                    target_policy = graph.resources[target_resource_id]
                    
                solver = Solver()
                res_tuple = encode_iam_scope_symbolic(target_policy.rule_sources)
                if isinstance(res_tuple, Unresolved):
                    actual_state = "UNRESOLVABLE"
                else:
                    act_v, res_v, expr = res_tuple
                    solver.add(expr)
                    res = solver.check()
                    actual_state = "SAT" if res == sat else ("UNSAT" if res == unsat else "UNKNOWN")
                
                if actual_state != expected_state:
                    errors.append(f"[IAM Differential Mismatch] {file_path} ({target_policy.address}): expected {expected_state}, got {actual_state}")

            elif vulnerability_class == "PRIVILEGE_ESCALATION_PATH":
                result = engine.verify_privilege_escalation(graph)
                actual_state = result.status
                if actual_state != expected_state:
                    errors.append(f"[Reachability Differential Mismatch] {file_path}: expected {expected_state}, got {actual_state}")
                    
        except Exception as e:
            errors.append(f"Exception in differential check for {file_path}: {e}")
            
    return (len(errors) == 0, errors)
